const client = new Client({
  authStrategy: new LocalAuth(),
  puppeteer: {
    args: [
      '--no-sandbox',
      '--disable-setuid-sandbox',
      '--disable-dev-shm-usage',
      '--disable-gpu',
      '--no-first-run',
      '--no-zygote',
      '--single-process',
    ],
  },
});

client.on('qr', (qr) => {
  currentQR = qr;
  isReady = false;
  console.log('QR-код обновлён — открой сайт бота и отсканируй');
});

client.on('ready', () => {
  isReady = true;
  currentQR = null;
  console.log('Бот готов к работе!');
});

client.on('auth_failure', () => console.error('Ошибка авторизации'));
client.on('disconnected', () => {
  isReady = false;
  console.log('Бот отключён');
});

client.on('message', async (message) => {
  if (message.fromMe || message.isStatus) return;
  if (message.from.endsWith('@g.us')) return;

  const userId = message.from;
  const userText = message.body.trim();

  if (!userText) return;

  if (userText.toLowerCase() === '/reset') {
    chatHistories.delete(userId);
    await message.reply('История очищена!');
    return;
  }

  const chat = await message.getChat();
  await chat.sendStateTyping();

  try {
    if (!chatHistories.has(userId)) chatHistories.set(userId, []);
    const history = chatHistories.get(userId);

    history.push({ role: 'user', parts: [{ text: userText }] });
    if (history.length > MAX_HISTORY) history.splice(0, history.length - MAX_HISTORY);

    const geminiChat = model.startChat({
      history: history.slice(0, -1),
      systemInstruction: {
        parts: [{ text: SYSTEM_PROMPT }]
      },
    });

    const result = await geminiChat.sendMessage(userText);
    const responseText = result.response.text();

    history.push({ role: 'model', parts: [{ text: responseText }] });

    // Убираем теги из сообщения клиенту
    const cleanResponse = responseText
      .replace(/\[HOT_LEAD:[^\]]*\]/g, '')
      .replace(/\[WARM_LEAD:[^\]]*\]/g, '')
      .trim();
    await message.reply(cleanResponse);

    const managerNumber = '77711231541@c.us';

    // Горячий клиент
    if (responseText.includes('[HOT_LEAD:')) {
      const match = responseText.match(/\[HOT_LEAD:\s*имя=([^,]+),\s*тел=([^\]]+)\]/);
      if (match) {
        const clientName = match[1].trim();
        const clientPhone = match[2].trim();
        const notify = `ГОРЯЧИЙ КЛИЕНТ\n\nИмя: ${clientName}\nТелефон: ${clientPhone}\nВремя: ${new Date().toLocaleString('ru-RU')}\n\nКлиент хочет оформить договор — свяжитесь как можно скорее!`;
        await client.sendMessage(managerNumber, notify);
      }
    }

    // Теплый клиент
    if (responseText.includes('[WARM_LEAD:')) {
      const match = responseText.match(/\[WARM_LEAD:\s*имя=([^,]+),\s*тел=([^\]]+)\]/);
      if (match) {
        const clientName = match[1].trim();
        const clientPhone = match[2].trim();
        const notify = `ТЕПЛЫЙ КЛИЕНТ\n\nИмя: ${clientName}\nТелефон: ${clientPhone}\nВремя: ${new Date().toLocaleString('ru-RU')}\n\nКлиент думает, нужно "дожать" — свяжитесь и ответьте на вопросы.`;
        await client.sendMessage(managerNumber, notify);
      }
    }

    console.log(`${userId}: ${userText.substring(0, 50)}`);
  } catch (error) {
    console.error('Ошибка:', error.message);
    await message.reply('Произошла ошибка, попробуйте ещё раз.');
  }
});

